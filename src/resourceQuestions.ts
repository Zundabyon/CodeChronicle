// Original examples for Laravel's ordinary web Route::resource, not apiResource.
// Controller snippets omit imports; Request, Villager and Post are configured classes.
// The illustrated changes are learning snapshots. No PHP or database command runs here.
export type ResourceTrial = {
  afterStep: string;
  room: number;
  unit: 'r' | 'u' | 'c' | 'd' | 'checkpoint';
  intro: string;
  question: Question;
  study: QuestStudy;
};
const table = (columns: string[], rows: string[][]): TableSnapshot => ({ columns, rows });
