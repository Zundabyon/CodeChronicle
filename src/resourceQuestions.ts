const duplicate = table(villagers.columns, [['7', 'ソラ', '南通り'], ['8', 'ソラ', '南通り'], ['9', 'ミナ', '東通り']]);
const deduplicated = table(villagers.columns, [['7', 'ソラ', '南通り'], ['9', 'ミナ', '東通り']]);
const posts = table(['id', 'title', 'user_id'], [['71', '宿の修理人募集', '6'], ['86', '焚火の講習', '9']]);
const material = table(['id', 'name', 'stock'], [['41', '青い鉱石', '6'], ['42', '赤い鉱石', '3']]);
let ordinal = 0;
function trial(unit: ResourceTrial['unit'], room: number, afterStep: string, id: string, action: ResourceAction,
  objective: string, intro: string, prompt: string, correct: string, distractors: [string, string, string],
  explanation: string, result: string, code?: string, before: TableSnapshot = villagers,
  after: TableSnapshot = before, request?: string, beginner = false): ResourceTrial {
  const options = [correct, ...distractors];
  const answer = ordinal++ % 4;
  options.splice(answer, 0, options.shift()!);
  return {
    unit, room, afterStep, intro,
    question: {
      id, kind: 'choice', topic: 'laravel', difficulty: beginner ? 'beginner' : 'intermediate',
      prompt, options: options as [string, string, string, string], answer, reveal: correct,
      explanation, ...(code ? { code, filename: 'Laravel / コントローラとルートの抜粋' } : {}),
    },
    study: { objective, action, before, after, result, ...(request ? { request } : {}), mode: room === 4 || unit === 'checkpoint' ? 'checkpoint' : 'practice' },
  };
}
