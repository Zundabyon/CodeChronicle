import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createServer } from 'vite';

const quote = value => `'${String(value).replaceAll("'", "''")}'`;
export function catalogArtifacts(questions) {
  // Canonical order makes exports reproducible, independent of authored order.
  const sorted = [...questions].sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  const payloads = sorted.map(q => JSON.stringify(Object.fromEntries(Object.entries(q).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0))));
  const version = `game-${createHash('sha256').update(JSON.stringify(payloads)).digest('hex').slice(0, 24)}`;
  const release = quote(version);
  const sql = [
    '-- Generated by npm run catalog:export. Apply with wrangler d1 execute --file seed.game.sql.',
    '-- Append-only revisions; repeat imports preserve published releases and timestamps.',
    `INSERT OR IGNORE INTO catalog_releases (version, status) VALUES (${release}, 'draft');`,
  ];
  for (let i = 0; i < sorted.length; i++) {
    const id = quote(sorted[i].id), payload = quote(payloads[i]);
    sql.push(`INSERT INTO question_revisions (question_id, revision, payload_json) SELECT ${id}, COALESCE((SELECT MAX(revision) FROM question_revisions WHERE question_id = ${id}), 0) + 1, ${payload} WHERE NOT EXISTS (SELECT 1 FROM question_revisions WHERE question_id = ${id} AND payload_json = ${payload});`);
    sql.push(`INSERT OR IGNORE INTO catalog_entries (catalog_version, question_id, question_revision) SELECT ${release}, ${id}, revision FROM question_revisions WHERE question_id = ${id} AND payload_json = ${payload} ORDER BY revision LIMIT 1;`);
  }
  sql.push(`UPDATE catalog_releases SET status = 'published', published_at = COALESCE(published_at, strftime('%Y-%m-%dT%H:%M:%fZ', 'now')) WHERE version = ${release} AND (SELECT COUNT(*) FROM catalog_entries WHERE catalog_version = ${release}) = ${sorted.length};`);
  return { version, sql: sql.join('\n') + '\n' };
}

export async function exportCatalog() {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const server = await createServer({ root, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom', optimizeDeps: { noDiscovery: true, include: [] } });
  try {
    const { questions } = await server.ssrLoadModule('/src/content.ts');
    const { parseQuestionCatalog } = await server.ssrLoadModule('/src/questionCatalog.ts');
    parseQuestionCatalog({ catalogVersion: 'export-check', questions });
    const { questDefinitions } = await server.ssrLoadModule('/src/quests/definitions.ts');
    const { questionBookLinks } = await server.ssrLoadModule('/src/bookQuestions.ts');
    const byId = new Map(questions.map(q => [q.id, q]));
    const required = [...Object.keys(questionBookLinks), ...questDefinitions.flatMap(def => def.steps.filter(step => step.trigger.type === 'question-answered').map(step => step.trigger.questionId))];
    for (const id of required) if (!byId.get(id)?.options) throw new Error(`Missing choice question for book/quest: ${id}`);
    const { version, sql } = catalogArtifacts(questions);
    writeFileSync(resolve(root, 'seed.game.sql'), sql);
    writeFileSync(resolve(root, 'src/catalogRelease.ts'), `// Generated with seed.game.sql by npm run catalog:export.\nexport const catalogVersion = ${JSON.stringify(version)};\n`);
    console.log(`Exported ${questions.length} questions: ${version} -> seed.game.sql`);
  } finally { await server.close(); }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await exportCatalog();
